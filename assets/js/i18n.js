  function getLang() {
    try { return localStorage.getItem("mi-lang") || "zh"; } catch (e) { return "zh"; }
  }

  function applyLang(lang) {
    lang = lang || getLang();
    var dict = I18N[lang] || I18N.zh;
    document.documentElement.lang = (lang === "en" ? "en" : "zh-CN");

    // 文本 / HTML 内容
    var nodes = document.querySelectorAll("[data-i18n]");
    for (var i = 0; i < nodes.length; i++) {
      var el = nodes[i];
      var key = el.getAttribute("data-i18n");
      if (!dict[key]) continue;
      if (el.hasAttribute("data-i18n-html")) {
        el.innerHTML = dict[key];
      } else {
        el.textContent = dict[key];
      }
    }

    // 属性翻译（仅 attr，不覆盖文本）
    var attrNodes = document.querySelectorAll("[data-i18n-attr]");
    for (var j = 0; j < attrNodes.length; j++) {
      var ae = attrNodes[j];
      var pairs = ae.getAttribute("data-i18n-attr").split(",");
      for (var p = 0; p < pairs.length; p++) {
        var kv = pairs[p].split(":");
        var attr = kv[0].trim();
        var vkey = (kv[1] || kv[0]).trim();
        if (dict[vkey]) ae.setAttribute(attr, dict[vkey]);
      }
    }

    // 切换按钮文案：显示「另一种语言」
    var btn = document.getElementById("langToggle");
    if (btn) btn.textContent = (lang === "en" ? "中" : "EN");

    try { localStorage.setItem("mi-lang", lang); } catch (e) {}
    document.documentElement.setAttribute("data-lang", lang);
  }

  function toggleLang() {
    var next = getLang() === "en" ? "zh" : "en";
    applyLang(next);
  }

  // 暴露 API
  window.MI = { I18N: I18N, getLang: getLang, applyLang: applyLang, toggleLang: toggleLang };

  // 首次自动应用（页面静态内容已在 DOM）
  function boot() { applyLang(getLang()); }
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", boot);
  } else {
    boot();
  }
